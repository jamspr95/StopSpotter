-- StopSpotter — SiteFinder settings UI (admin portal)
--
-- Jamie, 17 Oct 2026: "We need to be about to config all scoring
-- thresholds. These should be in the config / settings ui in the admin
-- portal." Decided (AskUserQuestion, same day) against guessing: (1) the
-- admin-edited value here is the single source of truth, pulled DOWN into
-- SiteFinder's real config/*.yaml by a sync script run before a pipeline
-- run (scripts/sync_config_from_stopspotter.py on that side) rather than
-- the pipeline reading this table live - so a changed threshold shows up
-- as a normal, reviewable git diff, and a pipeline run never needs
-- database credentials of its own; (2) numeric thresholds only -
-- owners.yaml's text name-patterns stay a YAML file only edited by hand,
-- since a typo there could silently stop recognising a whole category of
-- public land and needs a different kind of editor.
--
-- One row per tunable (site_rules.yaml/scoring.yaml's numeric leaves -
-- see SiteFinder's config/tunable_settings.yaml, the manifest this
-- table's seed data below is generated from), not one JSONB blob per
-- file - so the admin screen can list, label and describe each one
-- individually without the UI needing to know SiteFinder's own YAML
-- shape.
create table public.site_finder_settings (
  key text primary key,
  value numeric not null,
  group_name text not null,
  label text not null,
  description text,
  unit text,
  default_value numeric not null,
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users (id)
);

comment on table public.site_finder_settings is 'Admin-editable SiteFinder pipeline thresholds (site_rules.yaml/scoring.yaml numeric leaves only - see that repo''s config/tunable_settings.yaml). Read down into the real YAML by scripts/sync_config_from_stopspotter.py before a pipeline run - this table is never read live by the pipeline itself.';

-- RLS enabled, no policies - same "admin access only through a
-- SECURITY DEFINER RPC" pattern already used for public.admins and
-- friends (see the security advisor's own "RLS Enabled No Policy" INFO
-- finding, which already lists that table). service_role (the sync
-- script's own credential) bypasses RLS entirely, same as every other
-- admin-only table here.
alter table public.site_finder_settings enable row level security;

revoke all on public.site_finder_settings
from
  public,
  anon,
  authenticated;

create function public.admin_list_site_finder_settings () returns table (
  key text,
  value numeric,
  group_name text,
  label text,
  description text,
  unit text,
  default_value numeric,
  updated_at timestamptz
) language plpgsql stable security definer
set
  search_path = public as $$
begin
  if not current_user_is_admin () then
    raise exception 'not authorized';
  end if;

  return query
  select
    s.key, s.value, s.group_name, s.label, s.description, s.unit,
    s.default_value, s.updated_at
  from public.site_finder_settings s
  order by s.group_name, s.label;
end;
$$;

revoke execute on function public.admin_list_site_finder_settings ()
from
  public,
  anon,
  authenticated;

grant
execute on function public.admin_list_site_finder_settings () to authenticated;

create function public.admin_update_site_finder_setting (p_key text, p_value numeric) returns void language plpgsql security definer
set
  search_path = public as $$
begin
  if not current_user_is_admin () then
    raise exception 'not authorized';
  end if;

  update public.site_finder_settings
  set
    value = p_value,
    updated_at = now (),
    updated_by = auth.uid ()
  where
    key = p_key;

  if not found then
    raise exception 'unknown setting key: %', p_key;
  end if;
end;
$$;

revoke execute on function public.admin_update_site_finder_setting (text, numeric)
from
  public,
  anon,
  authenticated;

grant
execute on function public.admin_update_site_finder_setting (text, numeric) to authenticated;

